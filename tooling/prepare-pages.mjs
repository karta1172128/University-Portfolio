import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pages } from '../src/data/pages.js';
import { assertValidContent, projectRoot } from './content.js';

const escapeHtml = value => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

export function renderEntry(page) {
  const prefix = relative(dirname(page.path), '.').replaceAll('\\', '/');
  const path = file => prefix ? `${prefix}/${file}` : file;
  return `<!doctype html>
<!-- Generated by tooling/prepare-pages.mjs. Edit src/data/ instead. -->
<html lang="zh-Hant">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta name="description" content="${escapeHtml(page.description)}" />
  <link rel="icon" href="${path('images/logo.ico')}" />
  <title>${escapeHtml(page.title)}</title>
</head>
<body data-page="${escapeHtml(page.id)}"${page.id === 'home' ? ' class="resume-home"' : ''}>
  <div id="root"></div>
  <noscript>此網站需要 JavaScript 才能顯示履歷與作品，請啟用後重新整理。</noscript>
  <script type="module" src="${path('src/main.jsx')}"></script>
</body>
</html>
`;
}

export function preparePages() {
  assertValidContent();
  for (const page of pages) {
    const file = resolve(projectRoot, page.path);
    const html = renderEntry(page);
    if (existsSync(file) && readFileSync(file, 'utf8').replaceAll('\r\n', '\n') === html) continue;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, html);
  }
  console.log(`Prepared ${pages.length} HTML entries from portfolio data.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) preparePages();
